const { test } = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')

const read = (path) => readFileSync(path, 'utf8')

test('product-page quote CTA carries product name and canonical page into the quote form', () => {
  const actions = read('components/products/product-card-actions.tsx')
  const quotePage = read('app/quote/page.tsx')
  const route = read('app/api/quote/route.ts')
  assert.match(actions, /productName,/)
  assert.match(actions, /productUrl: detailsHref/)
  assert.match(quotePage, /setProductOfInterest\(name\)/)
  assert.match(quotePage, /productName: productOfInterest/)
  assert.match(quotePage, /productUrl,/)
  assert.match(route, /productName: d\.productName/)
  assert.match(route, /productUrl: d\.productUrl/)
})

test('product links persist without overwriting existing quote/customer data', () => {
  const followup = read('lib/followup.ts')
  const health = read('lib/admin-health.ts')
  assert.match(followup, /ADD COLUMN IF NOT EXISTS product_name text/)
  assert.match(followup, /ADD COLUMN IF NOT EXISTS product_url text/)
  assert.match(followup, /product_name, product_url/)
  assert.match(followup, /input\.productName \|\| null/)
  assert.match(followup, /input\.productUrl \|\| null/)
  assert.match(health, /ADD COLUMN IF NOT EXISTS product_name text/)
  assert.match(health, /ADD COLUMN IF NOT EXISTS product_url text/)
  assert.doesNotMatch(health.slice(health.indexOf('const REPAIR_SQL'), health.indexOf('export async function repairDatabase')), /DROP TABLE|DELETE FROM public\.(leads|orders)/i)
})

