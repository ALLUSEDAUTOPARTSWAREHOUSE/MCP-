test('customer dashboard uses authenticated database-scoped orders and quotes instead of fake browser tokens', () => {
  const route = read('app/api/customer/dashboard/route.ts')
  const dashboard = read('app/customer/dashboard/page.tsx')
  const login = read('app/api/customer/auth/login/route.ts')
  const signup = read('app/api/customer/auth/signup/route.ts')
  assert.match(route, /auth\.api\.getSession\(\{ headers: request\.headers \}\)/)
  assert.match(route, /WHERE userid = \$1 AND userid <> \$2/)
  assert.match(route, /WHERE user_id = \$1/)
  assert.match(route, /Cache-Control.*private, no-store/)
  assert.match(dashboard, /fetch\('\/api\/customer\/dashboard'/)
  assert.match(dashboard, /My quote requests/)
  assert.doesNotMatch(dashboard, /localStorage|customerToken|ORD-001234|TRK123456789/)
  assert.match(login, /status: 410/)
  assert.match(signup, /status: 410/)
})


